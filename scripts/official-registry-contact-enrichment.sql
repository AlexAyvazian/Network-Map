-- Additive, non-destructive multi-email enrichment for an official country registry.
-- Apply to ARGENTINA_REGISTRY_DATABASE_URL first; future country registries can reuse it.
--
-- Deliberately NO foreign key from these tables to official_registry_providers:
-- scripts/import-official-registry.sh and lib/db/scripts/import-official-registry.mjs
-- TRUNCATE/replace provider snapshots. Stable REFES source_record_id is the join key.
-- This schema retains contacts across refreshes, including while provider records
-- temporarily disappear; only matched facility contacts are exposed in the view.
--
-- Each publicly listed email belongs to ONE contact row per facility, with any
-- number of independent evidence URLs. The same email may appear at multiple
-- facilities ONLY where it is explicitly documented for each one.
CREATE TABLE IF NOT EXISTS public.official_registry_contact_emails (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id text NOT NULL CHECK (length(btrim(source_record_id)) > 0),
  email text NOT NULL CHECK (
    length(email) BETWEEN 5 AND 320
    AND position('@' in email) > 1
    AND position(' ' in email) = 0
  ),
  normalized_email text GENERATED ALWAYS AS (lower(btrim(email))) STORED,
  purposes text[] NOT NULL DEFAULT ARRAY['general']::text[],
  source_status text NOT NULL
    CHECK (source_status IN ('official_published','historical_published','candidate_unreviewed')),
  match_basis text NOT NULL
    CHECK (match_basis IN ('exact_facility_name_and_address','exact_refes_code','official_explicit_facility','website_facility_match','manual_review')),
  delivery_verified boolean NOT NULL DEFAULT false,
  first_discovered_at timestamptz NOT NULL DEFAULT now(),
  last_source_checked_at timestamptz,
  notes text,
  CONSTRAINT official_registry_contact_emails_unique UNIQUE (source_record_id, normalized_email)
);

CREATE TABLE IF NOT EXISTS public.official_registry_contact_email_evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_email_id bigint NOT NULL REFERENCES public.official_registry_contact_emails(id) ON DELETE CASCADE,
  source_url text NOT NULL CHECK (source_url ~ '^https?://'),
  source_title text,
  documented_purpose text,
  page_published_at date,
  observed_at timestamptz NOT NULL DEFAULT now(),
  evidence_note text,
  CONSTRAINT official_registry_contact_email_evidence_unique UNIQUE (contact_email_id, source_url)
);

-- Track attempted facility websites independently of the registry snapshot.
-- Resuming a batch never deletes or duplicates previously found contacts.
CREATE TABLE IF NOT EXISTS public.official_registry_contact_crawl_state (
  source_record_id text PRIMARY KEY,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  pages_scanned integer NOT NULL DEFAULT 0 CHECK (pages_scanned >= 0),
  candidate_email_count integer NOT NULL DEFAULT 0 CHECK (candidate_email_count >= 0)
);

CREATE INDEX IF NOT EXISTS official_registry_contact_emails_record_idx
  ON public.official_registry_contact_emails (source_record_id, source_status);

CREATE OR REPLACE VIEW public.official_registry_providers_with_contacts AS
SELECT p.*,
  COALESCE((
    SELECT jsonb_agg(
      jsonb_build_object(
        'email', c.email,
        'purposes', c.purposes,
        'source_status', c.source_status,
        'delivery_verified', c.delivery_verified,
        'last_source_checked_at', c.last_source_checked_at,
        'sources', COALESCE((
          SELECT jsonb_agg(
            jsonb_build_object(
              'url', e.source_url,
              'title', e.source_title,
              'purpose', e.documented_purpose,
              'page_published_at', e.page_published_at
            ) ORDER BY e.source_url
          )
          FROM public.official_registry_contact_email_evidence e
          WHERE e.contact_email_id = c.id
        ), '[]'::jsonb)
      ) ORDER BY c.email
    )
    FROM public.official_registry_contact_emails c
    WHERE c.source_record_id = p.source_record_id
      AND c.source_status IN ('official_published', 'historical_published')
  ), '[]'::jsonb) AS enriched_emails
FROM public.official_registry_providers p;
